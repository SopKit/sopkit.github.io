import { NextRequest } from "next/server";
import { getAllTools, getRelatedTools } from "@/lib/tools";
import { MANUAL_TOOL_CONTENT } from "@/data/generated-manual-content";
import { isCuratedContent } from "@/data/content-curation";
import { SITE_CONFIG, SITE_URL } from "@/constants/config";
import { buildCanonicalUrl } from "@/seo/canonical";

// This route is part of the static export (served from GitHub Pages), so it
// cannot set response headers and public/_headers is not honoured there. To
// keep the markdown mirror from becoming an indexable duplicate of every tool
// page, only curated tools (the ones whose HTML page advertises the markdown
// alternate) are exported; every other slug is simply absent from the build.
//
// The exported slug carries a `.md` extension: with `trailingSlash: true`
// an extensionless slug is written as a bare file that GitHub Pages cannot
// serve at `/tool-markdown/<id>/`, whereas `/tool-markdown/<id>.md` is a
// real file served with a text/markdown content type.
export const dynamic = "force-static";

const MARKDOWN_EXTENSION = ".md";

export async function generateStaticParams() {
	return getAllTools()
		.filter((t) => isCuratedContent(t.id))
		.map((t) => ({ slug: `${t.id}${MARKDOWN_EXTENSION}` }));
}

export async function GET(
	_request: NextRequest,
	props: { params: Promise<{ slug: string }> }
) {
	const params = await props.params;
	const slug = params.slug.endsWith(MARKDOWN_EXTENSION)
		? params.slug.slice(0, -MARKDOWN_EXTENSION.length)
		: params.slug;

	const allTools = getAllTools();
	const tool = allTools.find((t) => t.id === slug || t.route === `/${slug}`);

	if (!tool) {
		return new Response(`# Tool Not Found\n\nThe requested tool \`${slug}\` does not exist on SopKit.\n\nBrowse all tools at ${SITE_URL}/tools/\n`, {
			status: 404,
			headers: {
				"Content-Type": "text/markdown; charset=utf-8",
			},
		});
	}

	const canonical = buildCanonicalUrl(tool.route);
	const related = getRelatedTools(tool, 6);
	const isLocal = tool.executionType !== "external" && tool.id !== "ai-image-generator";

	const lines: string[] = [];
	lines.push(`# ${tool.name}`);
	lines.push("");
	lines.push(`> ${tool.description}`);
	lines.push("");
	lines.push(`- **Canonical URL**: ${canonical}`);
	lines.push(`- **Category**: ${tool.category || "Utility"}`);
	lines.push(`- **Execution Mode**: ${isLocal ? "Client-Side (Local Browser Sandbox — No File Uploads)" : "External API / Network Processing"}`);
	lines.push(`- **Access**: Free forever, no registration required`);
	lines.push("");

	// Prose sections appear only for tools whose content passed the uniqueness
	// audit. Every other tool gets the factual header plus related links.
	if (isCuratedContent(tool.id)) {
		const manual = MANUAL_TOOL_CONTENT[tool.id];
		const whatItIs = manual?.whatItIs || tool.article;
		const features = manual?.features || tool.features || [];
		const howTo = manual?.howToUse || tool.howTo;
		const faqs = manual?.faqs || tool.faqs || [];

		if (whatItIs) {
			lines.push("## About this Tool");
			lines.push("");
			lines.push(whatItIs);
			lines.push("");
		}

		if (features.length > 0) {
			lines.push("## Key Features");
			lines.push("");
			features.forEach((feat) => {
				lines.push(`- ${feat}`);
			});
			lines.push("");
		}

		if (howTo && howTo.steps && howTo.steps.length > 0) {
			lines.push(`## ${howTo.name || `How to Use ${tool.name}`}`);
			lines.push("");
			howTo.steps.forEach((step, idx) => {
				lines.push(`${idx + 1}. **${step.name}**: ${step.text}`);
			});
			lines.push("");
		}

		if (faqs.length > 0) {
			lines.push("## Frequently Asked Questions");
			lines.push("");
			faqs.forEach((faq) => {
				lines.push(`### ${faq.question}`);
				lines.push("");
				lines.push(faq.answer);
				lines.push("");
			});
		}
	}

	if (related.length > 0) {
		lines.push("## Related Tools");
		lines.push("");
		related.forEach((rel) => {
			lines.push(`- [${rel.name}](${buildCanonicalUrl(rel.route)}) — ${rel.description}`);
		});
		lines.push("");
	}

	lines.push("---");
	lines.push(`*Generated by SopKit (${SITE_CONFIG.siteUrl}) for search engines, AI agents, and LLM browsers.*`);

	return new Response(lines.join("\n"), {
		status: 200,
		headers: {
			"Content-Type": "text/markdown; charset=utf-8",
			"Cache-Control": "public, max-age=86400, stale-while-revalidate=604800",
		},
	});
}
