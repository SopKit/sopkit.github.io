#!/usr/bin/env node
/**
 * Writes src/constants/tool-stats.ts from src/constants/tools.json.
 *
 * src/constants/config.ts is imported by many "use client" components, so it
 * must not import tools.json (366 KB) itself. The counts are generated here at
 * build time (first prebuild step) and committed as plain numbers.
 *
 * Usage: node scripts/generate-tool-stats.mjs [--check]
 *   --check  exit 1 when the committed file is stale instead of rewriting it
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");
const toolsJsonPath = path.join(rootDir, "src", "constants", "tools.json");
const outputPath = path.join(rootDir, "src", "constants", "tool-stats.ts");

const registry = JSON.parse(readFileSync(toolsJsonPath, "utf8"));
const categories = registry.categories || {};
const allTools = Object.values(categories).flatMap((category) => category?.tools || []);

const stats = {
	toolCount: allTools.length,
	categoryCount: Object.keys(categories).length,
	popularToolCount: allTools.filter((tool) => tool?.popular).length,
};

const output = `// AUTO-GENERATED by scripts/generate-tool-stats.mjs from src/constants/tools.json.
// Do not edit by hand; run \`node scripts/generate-tool-stats.mjs\` (first prebuild step).
// Kept as plain numbers so client bundles never import the registry JSON.
export const TOOL_COUNT = ${stats.toolCount};
export const CATEGORY_COUNT = ${stats.categoryCount};
export const POPULAR_TOOL_COUNT = ${stats.popularToolCount};
`;

const checkOnly = process.argv.includes("--check");
let existing = "";
try {
	existing = readFileSync(outputPath, "utf8");
} catch {
	existing = "";
}

if (existing === output) {
	console.log(`tool-stats up to date (${stats.toolCount} tools, ${stats.categoryCount} categories, ${stats.popularToolCount} popular)`);
	process.exit(0);
}

if (checkOnly) {
	console.error("src/constants/tool-stats.ts is stale; run `node scripts/generate-tool-stats.mjs`");
	process.exit(1);
}

writeFileSync(outputPath, output);
console.log(`wrote src/constants/tool-stats.ts (${stats.toolCount} tools, ${stats.categoryCount} categories, ${stats.popularToolCount} popular)`);
