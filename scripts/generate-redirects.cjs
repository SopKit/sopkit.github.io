const fs = require("fs");
const path = require("path");

const BASE_DIR = path.join(__dirname, "..");
const REDIRECTS_DIR = path.join(BASE_DIR, "src", "seo", "redirects");
const publicRedirectsPath = path.join(BASE_DIR, "public", "_redirects");
const outDir = path.join(BASE_DIR, "out");

// Hand-maintained legacy redirects that predate the JSON manifests.
const MANUAL_REDIRECTS = [
	{ from: "/image-compressor-online", to: "/image-compressor", reason: "legacy alias" },
	{ from: "/pdf-to-word-converter", to: "/pdf-to-word", reason: "legacy alias" },
];

function normalizePath(p) {
	const trimmed = String(p).trim();
	if (!trimmed.startsWith("/")) throw new Error(`Redirect path must start with "/": ${trimmed}`);
	return trimmed.length > 1 && trimmed.endsWith("/") ? trimmed.slice(0, -1) : trimmed;
}

function loadManifests() {
	if (!fs.existsSync(REDIRECTS_DIR)) return [];
	return fs
		.readdirSync(REDIRECTS_DIR)
		.filter((file) => file.endsWith(".json"))
		.sort()
		.flatMap((file) => {
			const entries = JSON.parse(fs.readFileSync(path.join(REDIRECTS_DIR, file), "utf8"));
			if (!Array.isArray(entries)) throw new Error(`${file} must contain a JSON array`);
			return entries.map((entry) => ({ ...entry, source: file }));
		});
}

function buildRedirectsFile(entries) {
	const seen = new Map();
	const lines = [
		"# =============================================================================",
		"# Cloudflare _redirects file (AUTO-GENERATED by scripts/generate-redirects.cjs)",
		"# Source manifests: src/seo/redirects/*.json. Do not edit by hand.",
		"# =============================================================================",
		"",
	];
	for (const entry of entries) {
		const from = normalizePath(entry.from);
		const to = normalizePath(entry.to);
		if (from === to) throw new Error(`Redirect loops onto itself: ${from}`);
		if (seen.has(from) && seen.get(from) !== to) {
			throw new Error(`Conflicting redirects for ${from}: ${seen.get(from)} vs ${to}`);
		}
		if (seen.has(from)) continue;
		seen.set(from, to);
		const target = to === "/" ? "/" : `${to}/`;
		lines.push(`${from} ${target} 301`);
		lines.push(`${from}/ ${target} 301`);
	}
	lines.push("");
	return { content: lines.join("\n"), count: seen.size, map: seen };
}

function generateRedirects() {
	const entries = [...MANUAL_REDIRECTS, ...loadManifests()];
	// Chained redirects (a -> b -> c) are collapsed so every hop is a single 301.
	const { map } = buildRedirectsFile(entries);
	const flattened = entries.map((entry) => {
		let to = normalizePath(entry.to);
		const visited = new Set([normalizePath(entry.from)]);
		while (map.has(to) && !visited.has(to)) {
			visited.add(to);
			to = map.get(to);
		}
		return { ...entry, to };
	});
	const { content, count } = buildRedirectsFile(flattened);

	fs.writeFileSync(publicRedirectsPath, content);
	console.log(`Wrote ${count} redirects to public/_redirects`);

	if (fs.existsSync(outDir)) {
		fs.writeFileSync(path.join(outDir, "_redirects"), content);
		console.log("Copied _redirects into out/");
	}
}

generateRedirects();
